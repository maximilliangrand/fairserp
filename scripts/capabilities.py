"""Generate docs/CAPABILITIES.md from engine metadata. CI fails if the file is stale.

Usage: uv run python scripts/capabilities.py [--check]
"""

import sys
from pathlib import Path

from fairserp.config import Settings
from fairserp.engines import build_registry
from fairserp.model import OPTIONAL_PARAMS
from fairserp.rights import DISCLOSED

TARGET = Path(__file__).resolve().parent.parent / "docs" / "CAPABILITIES.md"

HEADER = """# Capability matrix

Generated by `scripts/capabilities.py` from each adapter's declared metadata. Do not edit
by hand. "Strict" means the engine runs under the default profile without an opt-in.
Rights reflect the providers' published terms as read on the review date; your own
agreement with a provider takes precedence. Not legal advice.

"""

SERPAPI = """
## SerpApi migration endpoint

| SerpApi feature | fairserp behavior |
|---|---|
| `engine=google`, `bing`, `duckduckgo`, ... | Refused unless mapped in `FAIRSERP_SERPAPI_ENGINES` (e.g. `google:auto`). fairserp never queries Google or Bing |
| `q`, `num`, `start`, `first`, `count` | Applied |
| `gl`/`cc`, `hl`, `mkt`, `kl` | Mapped to country/language; reported ignored when the answering engine cannot apply them |
| `safe=active` | Enforced. Engines that cannot filter are skipped; if none can, the request is refused (400) |
| `tbs=qdr:h/d/w/m/y`, `df` | Mapped to freshness when the engine supports it, else reported ignored. Other `tbs` values are reported ignored |
| `location` | Drives local results (OpenStreetMap) and engines that accept a location |
| `device`, `google_domain`, `uule`, `lr`, `cr`, `filter`, `nfpr`, `ludocid`, `kgmid`, ... | No equivalent; reported in `search_metadata.fairserp.params.ignored` |
| `fairserp_strict=true` | Reject instead of report when any param cannot be applied |
| `no_cache`, `async`, `zero_trace`, `output=json/html/md`, `json_restrictor` | Supported. `async` is refused for providers whose terms forbid storage; async jobs are not durable across restarts |
| `organic_results`, `knowledge_graph`, `answer_box`, `related_questions`, `related_searches`, `local_results`, `pagination`, `serpapi_pagination` | Rendered when a provider supplies them |
| `ai_overview` | Only for model-generated answers (Tavily), marked `fairserp_generated: true` |
| `ads`, `top_stories`, `shopping_results`, `inline_images`, Google verticals | Not available from any permitted source |
| Google rankings (rank tracking) | Not possible: fairserp results are not Google results |
"""


def render() -> str:
    settings = Settings(_env_file=None)
    registry = build_registry(load_plugins=False)
    lines = [HEADER, "## Engines", "",
             "| Engine | Role | Provenance | Strict | Commercial use | Max storage | Attribution "
             "| " + " | ".join(OPTIONAL_PARAMS) + " | Depth | Fixtures |",
             "|" + "---|" * (9 + len(OPTIONAL_PARAMS))]
    for engine in registry.values():
        rights = engine.rights_for(settings)
        storage = ("none (transient)" if rights.max_storage_seconds == 0 else
                   "no limit stated" if rights.max_storage_seconds is None else
                   f"{rights.max_storage_seconds // 60} min")
        strict = "yes" if rights.provenance in DISCLOSED and rights.commercial_use.value != \
            "noncommercial-only" else "opt-in"
        params = ["yes" if p in engine.supports else "-" for p in OPTIONAL_PARAMS]
        lines.append(
            f"| {engine.name} | {engine.role.value} | {rights.provenance.value} | {strict} "
            f"| {rights.commercial_use.value} | {storage} | {rights.attribution or '-'} | "
            + " | ".join(params)
            + f" | {engine.max_depth} | {'recorded' if engine.fixture_verified else 'unverified'} |"
        )
    lines += ["", "Terms reviewed per engine:", ""]
    for engine in registry.values():
        rights = engine.rights_for(settings)
        note = f" {rights.notes}" if rights.notes else ""
        lines.append(f"- **{engine.name}**: [{rights.terms_url}]({rights.terms_url}), "
                     f"reviewed {rights.terms_reviewed}.{note}")
    lines.append(SERPAPI)
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            raise SystemExit("docs/CAPABILITIES.md is stale: run scripts/capabilities.py")
    else:
        TARGET.write_text(text)
        print(f"wrote {TARGET}")
